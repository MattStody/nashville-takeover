-- Secrets generated and kept inside the database (Supabase Vault), so nobody
-- has to create, copy or paste them:
--   luma_webhook_token   part of the luma-webhook URL registered with Luma
--   internal_cron_token  sent by pg_cron to luma-sync as x-internal-token
-- Created on first use. Only the service role (edge functions) and the
-- database owner (pg_cron) can read them.
create function public.internal_secret(p_name text)
returns text
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_secret text;
begin
  if p_name not in ('luma_webhook_token', 'internal_cron_token') then
    raise exception 'unknown_secret' using errcode = '22023';
  end if;

  select decrypted_secret into v_secret from vault.decrypted_secrets where name = p_name;
  if v_secret is null then
    begin
      perform vault.create_secret(
        encode(extensions.gen_random_bytes(32), 'hex'), p_name, 'Generated by Nashville Takeover'
      );
    exception when unique_violation then
      null; -- created concurrently
    end;
    select decrypted_secret into v_secret from vault.decrypted_secrets where name = p_name;
  end if;
  return v_secret;
end;
$$;

revoke execute on function public.internal_secret(text) from public, anon, authenticated;
grant execute on function public.internal_secret(text) to service_role;
