import { generateMockDataset, type MockDataset } from '../luma/mock/fixtures.ts';
import { Rng } from '../luma/mock/random.ts';
import {
  SEED_CONTENT,
  SEED_EVENT_META,
  SEED_LINEUP,
  SEED_PERKS,
  SEED_SPONSORS,
  SEED_USERS,
} from './content.ts';

type SqlValue = string | number | boolean | null | string[];

function lit(v: SqlValue): string {
  if (v === null) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(lit).join(', ')}]::uuid[]`;
  return `'${v.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, SqlValue>[]): string {
  if (rows.length === 0) return '';
  const cols = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c] ?? null)).join(', ')})`).join(',\n');
  return `insert into ${table} (${cols.join(', ')}) values\n${values};\n`;
}

const addMinutes = (iso: string, min: number) => new Date(Date.parse(iso) + min * 60_000).toISOString();

/**
 * Builds supabase/seed.sql from the mock Luma dataset plus demo content, so the
 * database seed and the mock adapter always describe the same guests.
 */
export function generateSeedSql(dataset: MockDataset = generateMockDataset()): string {
  const rng = new Rng(2026);
  const out: string[] = [
    '-- GENERATED by `pnpm seed:generate` (packages/shared/src/seed). Do not edit by hand.',
    '-- Fake data only: every email is @example.com and every name is fictional.',
    '',
  ];

  // Users first, so guest rows link to accounts as they are inserted.
  const userIds = new Map<string, string>();
  const users = SEED_USERS.map((u) => {
    const id = rng.uuid();
    userIds.set(u.email, id);
    return { u, id };
  });
  out.push(
    insert(
      'auth.users',
      users.map(({ u, id }) => ({
        instance_id: '00000000-0000-0000-0000-000000000000',
        id,
        aud: 'authenticated',
        role: 'authenticated',
        email: u.email,
        encrypted_password: '',
        email_confirmed_at: '2026-10-01T00:00:00Z',
        confirmation_token: '',
        recovery_token: '',
        email_change_token_new: '',
        email_change: '',
        raw_app_meta_data: '{"provider":"email","providers":["email"]}',
        raw_user_meta_data: '{}',
        created_at: '2026-10-01T00:00:00Z',
        updated_at: '2026-10-01T00:00:00Z',
      })),
    ),
    insert(
      'auth.identities',
      users.map(({ u, id }) => ({
        id: rng.uuid(),
        provider_id: id,
        user_id: id,
        identity_data: JSON.stringify({ sub: id, email: u.email, email_verified: true }),
        provider: 'email',
        last_sign_in_at: '2026-10-01T00:00:00Z',
        created_at: '2026-10-01T00:00:00Z',
        updated_at: '2026-10-01T00:00:00Z',
      })),
    ),
  );
  for (const { u, id } of users) {
    out.push(
      `update public.profiles set display_name = ${lit(u.displayName)}, is_admin = ${lit(!!u.isAdmin)} where id = ${lit(id)};`,
    );
  }
  out.push('');

  dataset.events.forEach((mock, index) => {
    const meta = SEED_EVENT_META[index];
    if (!meta) throw new Error(`No SEED_EVENT_META for event ${index}`);
    const eventId = rng.uuid();
    const start = mock.event.startAt;
    out.push(`-- ${mock.event.name}`);
    out.push(
      insert('public.events', [
        {
          id: eventId,
          luma_event_id: mock.event.id,
          slug: meta.slug,
          name: mock.event.name,
          description: meta.description,
          starts_at: start,
          ends_at: mock.event.endAt,
          timezone: mock.event.timezone,
          venue_name: meta.venueName,
          venue_address: meta.venueAddress,
          status: meta.status,
          primary_color: meta.primaryColor,
          accent_color: meta.accentColor,
        },
      ]),
    );

    out.push(
      insert(
        'public.staff_assignments',
        SEED_USERS.flatMap((u) =>
          (u.assignments ?? [])
            .filter((a) => a.event === index)
            .map((a) => ({ user_id: userIds.get(u.email)!, event_id: eventId, role: a.role })),
        ),
      ),
    );

    const typeIds = new Map<string, string>();
    const typeIdsByName = new Map<string, string>();
    out.push(
      insert(
        'public.ticket_types',
        mock.ticketTypes.map((t, i) => {
          const id = rng.uuid();
          typeIds.set(t.id, id);
          typeIdsByName.set(t.name, id);
          return { id, event_id: eventId, luma_ticket_type_id: t.id, name: t.name, is_hidden: t.isHidden, sort_order: i };
        }),
      ),
    );

    const guestRows: Record<string, SqlValue>[] = [];
    const ticketRows: Record<string, SqlValue>[] = [];
    for (const g of mock.guests) {
      const guestId = rng.uuid();
      guestRows.push({
        id: guestId,
        event_id: eventId,
        luma_guest_id: g.id,
        guest_key: g.guestKey,
        name: g.name,
        email: g.email,
        approval_status: g.approvalStatus,
      });
      for (const t of g.tickets) {
        ticketRows.push({
          id: rng.uuid(),
          event_id: eventId,
          guest_id: guestId,
          ticket_type_id: typeIds.get(t.ticketTypeId)!,
          luma_ticket_id: t.id,
        });
      }
    }
    out.push(insert('public.guests', guestRows), insert('public.tickets', ticketRows));

    const perkRows: Record<string, SqlValue>[] = [];
    const mapRows: Record<string, SqlValue>[] = [];
    (SEED_PERKS[index] ?? []).forEach((p, i) => {
      const perkId = rng.uuid();
      perkRows.push({
        id: perkId,
        event_id: eventId,
        name: p.name,
        description: p.description,
        icon: p.icon,
        valid_from: p.window ? addMinutes(start, p.window.fromMin) : null,
        valid_until: p.window ? addMinutes(start, p.window.untilMin) : null,
        sort_order: i,
      });
      for (const [typeName, quantity] of Object.entries(p.allowances)) {
        const ticketTypeId = typeIdsByName.get(typeName);
        if (!ticketTypeId) throw new Error(`Unknown ticket type "${typeName}" for perk ${p.name}`);
        mapRows.push({ ticket_type_id: ticketTypeId, perk_id: perkId, event_id: eventId, quantity });
      }
    });
    out.push(insert('public.perks', perkRows), insert('public.ticket_type_perks', mapRows));

    out.push(
      insert(
        'public.lineup_items',
        (SEED_LINEUP[index] ?? []).map((s) => ({
          id: rng.uuid(),
          event_id: eventId,
          artist: s.artist,
          stage: s.stage,
          starts_at: addMinutes(start, s.startMin),
          ends_at: addMinutes(start, s.startMin + s.durationMin),
          description: s.description,
        })),
      ),
      insert(
        'public.event_content',
        (SEED_CONTENT[index] ?? []).map((c, i) => ({
          id: rng.uuid(),
          event_id: eventId,
          kind: c.kind,
          title: c.title,
          body: c.body,
          sort_order: i,
        })),
      ),
      insert(
        'public.sponsor_activations',
        (SEED_SPONSORS[index] ?? []).map((s, i) => ({
          id: rng.uuid(),
          event_id: eventId,
          sponsor_name: s.name,
          description: s.description,
          location: s.location,
          cta_url: s.ctaUrl ?? null,
          sort_order: i,
        })),
      ),
    );

    if (meta.status === 'published') {
      out.push(
        insert('public.notifications', [
          {
            id: rng.uuid(),
            event_id: eventId,
            title: 'Doors open soon',
            body: `Doors open at ${meta.venueName} in 30 minutes. Have your QR code ready.`,
            audience_ticket_type_ids: null,
            created_by: userIds.get('manager@example.com')!,
            sent_at: addMinutes(start, -30),
            sent_by: userIds.get('manager@example.com')!,
          },
        ]),
      );
    }
  });

  return out.filter((s) => s !== '').join('\n');
}
